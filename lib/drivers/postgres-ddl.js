/**
 * PostgreSQL DDL composition.
 *
 * Kept apart from the driver so the text can be unit-tested against fixture
 * metadata: everything here is pure string assembly. The driver's only job is to
 * gather the catalogue rows this expects.
 *
 * The output is what you would paste into a script to recreate the table:
 * a `CREATE TABLE` with the real column types, then the constraints, the
 * non-constraint indexes and the comments as separate statements — the same
 * split `pg_dump --schema-only` uses, and for the same reason: an inline
 * `PRIMARY KEY` cannot express a deferrable constraint.
 */

import { qualify, quoteIdent } from '../query.js'

/**
 * Render one column definition.
 * @param {object} column - `{ name, type, notNull, identity, generated, defaultDef }`.
 * @returns {string} the definition, without the trailing comma.
 */
function columnLine(column) {
  const parts = [quoteIdent('postgres', column.name), String(column.type ?? '')]
  if (column.generated === 's' && column.defaultDef) {
    // A generated column keeps its expression in `pg_attrdef` like a default.
    parts.push(`GENERATED ALWAYS AS (${column.defaultDef}) STORED`)
  } else {
    if (column.identity === 'a') parts.push('GENERATED ALWAYS AS IDENTITY')
    else if (column.identity === 'd') parts.push('GENERATED BY DEFAULT AS IDENTITY')
    if (column.notNull) parts.push('NOT NULL')
    if (column.defaultDef) parts.push(`DEFAULT ${column.defaultDef}`)
  }
  return parts.join(' ')
}

/**
 * Build the DDL for a view or materialized view.
 *
 * A view has no columns of its own to declare, so rendering one as a
 * `CREATE TABLE` would be actively misleading.
 * @param {{ schema: string, table: string, kind: string, definition: string, comment?: string }} input - metadata.
 * @returns {string} the DDL, or '' when the definition is missing.
 */
export function buildPostgresViewDdl(input) {
  const definition = String(input.definition ?? '').trim().replace(/;+$/, '')
  if (!definition) return ''
  const target = qualify('postgres', [input.schema, input.table])
  const kind = input.kind === 'm' ? 'MATERIALIZED VIEW' : 'VIEW'
  const statements = [`CREATE ${kind} ${target} AS\n${definition};`]
  if (input.comment) statements.push(`COMMENT ON ${kind} ${target} IS ${literal(input.comment)};`)
  return statements.join('\n\n')
}

/**
 * Build the DDL for one table.
 * @param {{ schema: string, table: string, columns: object[], constraints?: object[],
 *   indexes?: object[], tableComment?: string }} input - catalogue metadata.
 * @returns {string} the DDL, or '' when there are no columns.
 */
export function buildPostgresDdl(input) {
  const columns = Array.isArray(input.columns) ? input.columns : []
  if (columns.length === 0) return ''
  const target = qualify('postgres', [input.schema, input.table])

  const statements = [`CREATE TABLE ${target} (\n${columns.map((column) => `  ${columnLine(column)}`).join(',\n')}\n);`]

  for (const constraint of input.constraints ?? []) {
    const definition = String(constraint.definition ?? '').trim()
    if (!definition) continue
    statements.push(
      `ALTER TABLE ${target} ADD CONSTRAINT ${quoteIdent('postgres', constraint.name)} ${definition};`,
    )
  }

  for (const index of input.indexes ?? []) {
    const definition = String(index.definition ?? '').trim()
    if (definition) statements.push(`${definition};`)
  }

  if (input.tableComment) {
    statements.push(`COMMENT ON TABLE ${target} IS ${literal(input.tableComment)};`)
  }
  for (const column of columns) {
    if (!column.comment) continue
    statements.push(
      `COMMENT ON COLUMN ${target}.${quoteIdent('postgres', column.name)} IS ${literal(column.comment)};`,
    )
  }

  return statements.join('\n\n')
}

/**
 * Quote a SQL string literal.
 * @param {string} value - the text.
 * @returns {string} the quoted literal.
 */
function literal(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`
}
