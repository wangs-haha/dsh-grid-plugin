/**
 * Unit tests for the PostgreSQL DDL composition.
 *
 * The driver only gathers catalogue rows; this file checks that the text those
 * rows produce is what would actually recreate the table — real types, identity
 * and generated columns, constraints as separate statements, non-constraint
 * indexes, and comments.
 */

import assert from 'node:assert/strict'
import { test } from 'node:test'

import { buildPostgresDdl } from '../lib/drivers/postgres-ddl.js'

test('columns carry their real type, nullability and default', () => {
  const ddl = buildPostgresDdl({
    schema: 'public',
    table: 'users',
    columns: [
      { name: 'id', type: 'bigint', notNull: true, defaultDef: "nextval('users_id_seq'::regclass)" },
      { name: 'email', type: 'text', notNull: true },
      { name: 'score', type: 'numeric(5,2)', notNull: false, defaultDef: '0' },
    ],
  })
  assert.equal(
    ddl,
    [
      'CREATE TABLE "public"."users" (',
      '  "id" bigint NOT NULL DEFAULT nextval(\'users_id_seq\'::regclass),',
      '  "email" text NOT NULL,',
      '  "score" numeric(5,2) DEFAULT 0',
      ');',
    ].join('\n'),
  )
})

test('identity and generated columns are distinguishable from defaults', () => {
  const ddl = buildPostgresDdl({
    schema: 'public',
    table: 'events',
    columns: [
      { name: 'id', type: 'bigint', notNull: true, identity: 'a' },
      { name: 'seq', type: 'integer', notNull: true, identity: 'd' },
      { name: 'label', type: 'text', notNull: false, generated: 's', defaultDef: '((kind)::text)' },
    ],
  })
  assert.match(ddl, /"id" bigint GENERATED ALWAYS AS IDENTITY/)
  assert.match(ddl, /"seq" integer GENERATED BY DEFAULT AS IDENTITY/)
  // A generated column keeps its expression in pg_attrdef; it must not be
  // rendered as a DEFAULT, and it must not be double-quoted as NOT NULL default.
  assert.match(ddl, /"label" text GENERATED ALWAYS AS \(\(\(kind\)::text\)\) STORED/)
  assert.ok(!/"label" text DEFAULT/.test(ddl))
})

test('constraints, indexes and comments are separate statements', () => {
  const ddl = buildPostgresDdl({
    schema: 'shop',
    table: 'orders',
    columns: [
      { name: 'id', type: 'bigint', notNull: true },
      { name: 'email', type: 'text', notNull: true, comment: "the buyer's login" },
    ],
    constraints: [
      { name: 'orders_pkey', type: 'p', definition: 'PRIMARY KEY (id)' },
      { name: 'orders_email_key', type: 'u', definition: 'UNIQUE (email)' },
      { name: 'orders_total_check', type: 'c', definition: 'CHECK ((total >= 0)) DEFERRABLE' },
      { name: 'orders_note', type: 'c', definition: '' },
    ],
    indexes: [
      { name: 'orders_lower_email_idx', definition: 'CREATE INDEX orders_lower_email_idx ON shop.orders USING btree (lower(email))' },
      { name: 'empty', definition: '' },
    ],
    tableComment: 'Checkout orders',
  })

  assert.match(ddl, /ALTER TABLE "shop"\."orders" ADD CONSTRAINT "orders_pkey" PRIMARY KEY \(id\);/)
  assert.match(ddl, /ADD CONSTRAINT "orders_email_key" UNIQUE \(email\);/)
  // Deferrable clauses survive, which is exactly why constraints are not inline.
  assert.match(ddl, /ADD CONSTRAINT "orders_total_check" CHECK \(\(total >= 0\)\) DEFERRABLE;/)
  // An empty definition is skipped rather than emitted as a broken statement.
  assert.ok(!/orders_note/.test(ddl))
  assert.match(ddl, /CREATE INDEX orders_lower_email_idx ON shop\.orders USING btree \(lower\(email\)\);/)
  assert.ok(!/INDEX\s+empty/.test(ddl))
  assert.match(ddl, /COMMENT ON TABLE "shop"\."orders" IS 'Checkout orders';/)
  assert.match(ddl, /COMMENT ON COLUMN "shop"\."orders"\."email" IS 'the buyer''s login';/)
})

test('a table with no columns has no DDL', () => {
  assert.equal(buildPostgresDdl({ schema: 'public', table: 'gone', columns: [] }), '')
  assert.equal(buildPostgresDdl({ schema: 'public', table: 'gone' }), '')
})

test('identifiers with quotes are escaped', () => {
  const ddl = buildPostgresDdl({
    schema: 'public',
    table: 'odd"name',
    columns: [{ name: 'a"b', type: 'text', notNull: false }],
  })
  assert.match(ddl, /^CREATE TABLE "public"\."odd""name" \(/)
  assert.match(ddl, /"a""b" text/)
})
